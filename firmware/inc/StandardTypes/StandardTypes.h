/******************************************************************************************************************************************************
 *  GLOBAL INLINE FUNCTIONS
******************************************************************************************************************************************************/
template <typename T>
uint8_t DigitsOfNumber(T number, unsigned base)
{
    T number_of_digits = 0u;

    do { number /= base; ++number_of_digits; }
    while (number != 0u);

    return number_of_digits;
}

